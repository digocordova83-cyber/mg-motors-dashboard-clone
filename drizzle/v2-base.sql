CREATE TABLE IF NOT EXISTS v2_accounts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  isActive BOOLEAN NOT NULL DEFAULT TRUE,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS v2_sources (
  id INT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  spreadsheetId VARCHAR(100) NOT NULL,
  importedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  totalRows INT NOT NULL,
  invalidDateRows INT NOT NULL,
  inputSha256 VARCHAR(64) NOT NULL
);
CREATE TABLE IF NOT EXISTS v2_leads (
  id INT AUTO_INCREMENT PRIMARY KEY,
  sourceSheet VARCHAR(100) NOT NULL,
  sourceRow INT NOT NULL,
  leadDate VARCHAR(10) NOT NULL,
  leadHour INT NULL,
  name VARCHAR(250) NOT NULL,
  model VARCHAR(250) NOT NULL,
  version VARCHAR(250) NOT NULL,
  channel VARCHAR(100) NOT NULL,
  campaign VARCHAR(500) NOT NULL,
  dealer VARCHAR(250) NOT NULL,
  city VARCHAR(250) NOT NULL,
  state VARCHAR(100) NOT NULL,
  crm VARCHAR(250) NOT NULL,
  UNIQUE KEY source_record (sourceSheet, sourceRow),
  INDEX by_date (leadDate),
  INDEX by_channel_date (channel, leadDate)
);
CREATE TABLE IF NOT EXISTS v2_lead_goals (
  competence VARCHAR(7) PRIMARY KEY,
  goal INT NOT NULL,
  updatedBy INT NOT NULL,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS v2_goal_audit (
  id INT AUTO_INCREMENT PRIMARY KEY,
  competence VARCHAR(7) NOT NULL,
  oldGoal INT NULL,
  newGoal INT NOT NULL,
  accountId INT NOT NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
